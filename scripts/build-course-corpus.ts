// Run: bun scripts/build-course-corpus.ts
import { writeFileSync } from "node:fs";
import { buildCourseCorpus } from "../src/lib/courseCorpus";

const corpus = buildCourseCorpus();
const body = `// AUTO-GENERATED by scripts/build-course-corpus.ts from src/lib/lessonData.ts — do not edit.\n` +
  `export const COURSE_CORPUS_VERSION = ${JSON.stringify(corpus.version)};\n` +
  `export const COURSE_CORPUS = ${JSON.stringify(corpus.entries, null, 2)} as const;\n`;
writeFileSync(new URL("../supabase/functions/_shared/courseCorpus.ts", import.meta.url), body);
console.log(`wrote ${corpus.entries.length} entries, version ${corpus.version}`);
